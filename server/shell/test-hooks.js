export function createTestHooks(hooks) {
  if (!hooks || typeof hooks !== "object") {
    throw new Error("test-hooks: hooks registry is required");
  }
  for (const key of TEST_HOOK_KEYS) {
    if (!(key in hooks)) {
      throw new Error(`test-hooks: missing ${key}`);
    }
  }
  return Object.freeze(hooks);
}
