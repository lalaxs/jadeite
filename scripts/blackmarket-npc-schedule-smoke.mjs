import assert from 'node:assert/strict';
import { performance } from 'node:perf_hooks';
import { NPC_TARGET_STALLS, NPC_MARKET_REFRESH_MS, npcRuleForStall } from '../shared/domain/blackmarket/npc-rules.js';
import { createMemoryWorldStore } from '../server/world-store.js';
process.env.JADE_WORLD_PERSIST='0';
const {__testHooks:H}=await import('../server.js');
const {maintainNpcBlackmarket}=await import('../server/services/blackmarket/npc.js');
const clock=Date.now; let now=clock(); Date.now=()=>now;
try {
 H.world.clear();
 const started=performance.now(); maintainNpcBlackmarket(now);
 const stalls=()=>H.state.blackStalls.filter(s=>s.npc);
 assert.equal(stalls().length,NPC_TARGET_STALLS);
 assert.equal(stalls().filter(s=>s.type==='blindbox').length,6);
 assert.ok(stalls().some(s=>npcRuleForStall(s).assortment?.includes('equipment')));
 for(const stall of stalls().filter(s=>s.type==='goods' && npcRuleForStall(s).assortment)) {
  assert.ok(new Set(stall.items.map(r=>r.npcSupplyRole)).size>=2, `${stall.title} keeps its mixed assortment`);
 }
 const initial=structuredClone(stalls());
 assert.equal(maintainNpcBlackmarket(now+1).changed,false);
 assert.deepEqual(stalls(),initial,'visits must not reroll the world');
 const buyer=H.makePlayer('dynamic-buyer'); buyer.cash=10000000; buyer.achievementPoints=buyer.achievementPointsBonus=9999; H.state.players.set(buyer.id,buyer);
 const other=H.makePlayer('dynamic-other'); other.cash=10000000; other.achievementPoints=other.achievementPointsBonus=9999; H.state.players.set(other.id,other);
 const stone=stalls().find(s=>s.id==='bm-npc:stone'); const row=stone.items[0];
 assert.equal(H.buyGoodsFromStallForPlayer(buyer,stone.id,row.id,row.price).ok,true);
 assert.equal(H.buyGoodsFromStallForPlayer(other,stone.id,row.id,row.price).ok,false,'shared stock is sold once');
 const blind=stalls().find(s=>s.type==='blindbox');
 const publicBlind=H.publicBlackStall(blind,other.id,H.publicStone);
 assert.equal(publicBlind.pool,undefined); assert.equal(publicBlind.poolCount,9);
 const cash=buyer.cash; const price=blind.blindPrice;
 const draw=H.startBlindboxDrawForPlayer(buyer,blind.id); assert.equal(draw.ok,true,draw.message);
 const picked=draw.draw.candidates[0].itemId;
 const result=H.settleBlindboxDrawForPlayer(buyer,{stallId:blind.id,drawId:draw.draw.id,selectedItemIds:[picked]});
 assert.equal(result.ok,true,result.message); assert.equal(buyer.cash,cash-price);
 assert.ok([...buyer.rough,...buyer.materials,...buyer.slices,...buyer.bracelets].some(i=>i.id===picked));
 assert.equal(H.state.players.size,2,'NPC merchants do not become player accounts');
 now=initial[0].npcMarketRefreshAt-1;
 const pending=H.startBlindboxDrawForPlayer(buyer,blind.id); assert.equal(pending.ok,true,pending.message);
 const frozenDraw=structuredClone(blind.blindDraw); const frozenPool=structuredClone(blind.pool); const blindPrice=blind.blindPrice;
 const before=new Map(stalls().map(s=>[s.id,structuredClone(s)]));
 now+=1; assert.equal(maintainNpcBlackmarket(now).changed,true);
 assert.equal(stalls().length,NPC_TARGET_STALLS);
 assert.ok(stalls().some(s=>!before.has(s.id)),'new merchants arrive');
 assert.ok([...before.keys()].some(id=>!stalls().some(s=>s.id===id)),'some merchants close');
 assert.ok(stalls().filter(s=>before.has(s.id)).length>=30,'most shelves remain in place');
 assert.ok(stalls().includes(blind)); assert.deepEqual(blind.blindDraw,frozenDraw); assert.deepEqual(blind.pool,frozenPool); assert.equal(blind.blindPrice,blindPrice);
 const stable=stalls().find(s=>before.has(s.id)&&s.type==='goods'&&s.items.length===before.get(s.id).items.length);
 assert.deepEqual(stable.items,before.get(stable.id).items,'unaffected stock keeps its identity and price');
 const world=createMemoryWorldStore(); world.importSnapshot(H.world.exportSnapshot());
 assert.equal(world.raw.blackStalls.filter(s=>s.npc).length,NPC_TARGET_STALLS);
 assert.equal(world.raw.blackStalls.find(s=>s.id===blind.id).blindDraw.id,frozenDraw.id);
 console.log(JSON.stringify({ok:true,stalls:stalls().length,blindStalls:6,refreshMs:NPC_MARKET_REFRESH_MS,sharedStock:true,blindSettlement:true,pendingDrawProtected:true,persistence:true,elapsedMs:Math.round(performance.now()-started)}));
} finally {Date.now=clock;}
