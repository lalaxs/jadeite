import assert from "node:assert/strict";
import { __testHooks as H } from "../server.js";
import { randomUUID } from "node:crypto";
import { bindBlackmarketApi, openBlackStallForPlayer, closeBlackStallForPlayer, addGoodsBatchToStallForPlayer, buyGoodsFromStallForPlayer, withdrawGoodsFromStallForPlayer, updateBlackStallMetaForPlayer, publicBlackStall, addBlindboxItemsForPlayer, maintainNpcBlackmarket, reconcileBlackmarketReferences } from "../server/services/blackmarket-service.js";
import { requireApi } from "../server/services/blackmarket/context.js";
import { bmSellables } from "../shared/domain/blackmarket/bm-plan-pool.js";
import { createMemoryWorldStore } from "../server/world-store.js";
import { workerDailyWage } from "../shared/domain/economy/worker-economy.js";
import { equipmentSaleBlockReason } from "../shared/domain/economy/equipment-trading.js";
import { installOwnedWorkshopFixture } from "./fixtures/owned-workshop.mjs";

const api = requireApi();
H.state.players.clear(); H.state.blackStalls.length = 0; H.state.blackServiceOrders.length = 0;
function player(id) {
  const p = installOwnedWorkshopFixture(H.makePlayer(id));
  for (const device of p.workshop.devices) device.resourceOrigin = "legacy-starter";
  H.normalizePlayer(p); p.cash = 10_000_000;
  p.assets.workshopOwned = true;
  H.state.players.set(p.id, p);
  return p;
}
const seller = player("resource-seller"), buyer = player("resource-buyer");
const equipment = H.buyEquipment(seller, H.equipmentCatalog()[1].modelKey, { spendCash: H.spendCash, makeId: randomUUID }).device;
equipment.condition = 61;
const recruited = H.recruitWorker(seller, seller.recruitCandidates[0].id, { spendCash: H.spendCash });
assert.equal(recruited.ok, true, recruited.message);
const worker = recruited.worker;
worker.skills.cut.jieliao.exp = 29;
const skills = structuredClone(worker.skills);
assert.equal(bmSellables({ me: seller }).find((item) => item.id === equipment.id)._type, "equipment");
assert.ok(bmSellables({ me: seller }).some((item) => item.resourceOrigin === "legacy-starter"));
assert.equal(openBlackStallForPlayer(seller, { type: "goods" }).ok, true);
const ownStall = () => H.state.blackStalls.find((s) => s.ownerId === seller.id);
const list = (type, item, price = 18000) => addGoodsBatchToStallForPlayer(seller, [{ type, itemId: item.id, price }]);
seller.jobs.push({ id: "busy-job", deviceId: equipment.id, workerId: worker.id });
assert.equal(list("employee", worker).ok, false);
assert.equal(list("equipment", equipment).ok, false);
seller.jobs.length = 0;
seller.livestreamRoom = { ...seller.livestreamRoom, status: "live", hostWorkerId: worker.id };
assert.equal(list("employee", worker).ok, false);
seller.livestreamRoom.status = "idle";
H.state.blackServiceOrders.push({ id: "reserved", sellerId: seller.id, status: "pending" });
assert.equal(list("equipment", equipment).ok, false);
H.state.blackServiceOrders.length = 0;
assert.equal(addGoodsBatchToStallForPlayer(seller, [{ type: "employee", itemId: worker.id, price: 18000 }, { type: "equipment", itemId: "missing", price: 100 }]).ok, false);
assert.equal(worker.blackmarketListingId, undefined, "partial batch unlocks the first resource");
assert.equal(list("employee", worker).ok, true);
assert.equal(seller.workshop.workers.length, 5, "listing continues to consume a roster slot");
assert.equal(H.isWorkerBusy(seller, worker.id), true);
assert.equal(H.dismissWorker(seller, worker.id, { spendCash: H.spendCash }).ok, false);
assert.equal(list("employee", worker).ok, false);
assert.equal(bmSellables({ me: seller }).some((item) => item.id === worker.id), false);
const workerRow = ownStall().items.find((row) => row.type === "employee");
assert.equal(publicBlackStall(ownStall(), buyer.id).items[0].item.acquisitionPrice, undefined);
assert.equal(list("equipment", equipment, 12000).ok, true);
let deviceRow = ownStall().items.find((row) => row.type === "equipment");
assert.equal(H.repairEquipment(seller, equipment.id, { spendCash: H.spendCash }).ok, false);
assert.match(equipmentSaleBlockReason(seller, equipment, H.state), /黑市/);
assert.equal(H.startWorkshopJobForPlayer(seller, equipment.id, {}).code, "RESOURCE_LISTED");
assert.equal(updateBlackStallMetaForPlayer(seller, { listingId: deviceRow.id, price: 13500 }).ok, true);
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, deviceRow.id, 12000).code, "PRICE_CHANGED");
const sellerBefore = structuredClone(seller), buyerBefore = structuredClone(buyer);
bindBlackmarketApi({ ...api, earnCash() { throw new Error("injected payout failure"); } });
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, deviceRow.id, 13500).ok, false);
assert.deepEqual(seller, sellerBefore); assert.deepEqual(buyer, buyerBefore);
bindBlackmarketApi(api);
deviceRow = ownStall().items.find((row) => row.type === "equipment");
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, deviceRow.id, 13500).ok, true);
assert.equal(buyer.workshop.devices.find((item) => item.id === equipment.id).condition, 61);
assert.equal(buyer.workshop.devices.find((item) => item.id === equipment.id).costBasis.amount, 13500);
assert.equal(seller.workshop.devices.some((item) => item.id === equipment.id), false);
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, deviceRow.id).ok, false);
buyer.employeePayroll.debt = 100;
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, workerRow.id).ok, false);
buyer.employeePayroll.debt = 0;
const extra = structuredClone(buyer.workshop.workers[0]);
for (let i = 0; i < 4; i++) buyer.workshop.workers.push({ ...extra, id: randomUUID() });
assert.equal(buyGoodsFromStallForPlayer(buyer, ownStall().id, workerRow.id).ok, false);
buyer.workshop.workers.splice(4);
const stallId = ownStall().id;
const beforePayrollFailure = structuredClone({ seller, buyer, stalls: H.state.blackStalls });
bindBlackmarketApi({ ...api, spendCash(p, amount, label, meta) {
  if (p.id === seller.id && meta?.source === "employeeSalary") throw new Error("injected payroll payment failure");
  return api.spendCash(p, amount, label, meta);
} });
assert.equal(buyGoodsFromStallForPlayer(buyer, stallId, workerRow.id, 18000).ok, false);
assert.deepEqual({ seller, buyer, stalls: H.state.blackStalls }, beforePayrollFailure);
bindBlackmarketApi(api);
assert.equal(buyGoodsFromStallForPlayer(buyer, stallId, workerRow.id, 18000).ok, true);
const received = buyer.workshop.workers.find((item) => item.id === worker.id);
assert.deepEqual(received.skills, skills);
assert.equal(H.snapshotFor(buyer).me.workshop.workers.find((item) => item.id === worker.id).tradeHistory, undefined, "internal transfer identities must not reveal anonymous sellers to the client");
assert.equal(received.blackmarketListingId, undefined);
assert.equal(seller.workshop.workers.some((item) => item.id === worker.id), false);
assert.ok(seller.employeePayroll.currentBill.entries.find((entry) => entry.workerId === worker.id).booked, "seller departure wage is settled");
assert.equal(buyer.employeePayroll.currentBill.entries.find((entry) => entry.workerId === worker.id).dailyWage, workerDailyWage(worker));
assert.ok(!buyer.bracelets.some((item) => item.id === worker.id));
assert.equal(buyGoodsFromStallForPlayer(buyer, stallId, workerRow.id).ok, false);

// Withdraw/close release the lock without adding a second roster copy; listed
// resource locks survive an actual snapshot validation and restoration.
assert.equal(openBlackStallForPlayer(buyer, { type: "goods" }).ok, true);
const buyerStall = () => H.state.blackStalls.find((s) => s.ownerId === buyer.id);
assert.equal(addGoodsBatchToStallForPlayer(buyer, [{ type: "employee", itemId: worker.id, price: 20000 }, { type: "equipment", itemId: equipment.id, price: 15000 }]).ok, true);
const store = createMemoryWorldStore({ players: H.state.players, blackStalls: H.state.blackStalls });
const snapshot = store.exportSnapshot({ savedAt: Date.now() });
const restored = createMemoryWorldStore(); restored.importSnapshot(structuredClone(snapshot));
bindBlackmarketApi({ ...api, getState: () => restored.raw });
reconcileBlackmarketReferences(restored.raw);
const restoredBuyer = restored.raw.players.get(buyer.id);
assert.ok(restoredBuyer.workshop.workers.find((item) => item.id === worker.id).blackmarketListingId);
bindBlackmarketApi(api);
const count = buyer.workshop.workers.length;
assert.equal(withdrawGoodsFromStallForPlayer(buyer, buyerStall().items.find((row) => row.type === "employee").id).ok, true);
assert.equal(buyer.workshop.workers.length, count);
assert.equal(received.blackmarketListingId, undefined);
assert.equal(closeBlackStallForPlayer(buyer).ok, true);
assert.equal(buyer.workshop.devices.find((item) => item.id === equipment.id).blackmarketListingId, undefined);
assert.equal(openBlackStallForPlayer(buyer, { type: "blindbox" }).ok, true);
assert.equal(addBlindboxItemsForPlayer(buyer, [{ type: "employee", itemId: worker.id }]).ok, false);
closeBlackStallForPlayer(buyer);

maintainNpcBlackmarket();
const talent = H.state.blackStalls.find((s) => s.npcRole === "employee");
const machines = H.state.blackStalls.find((s) => s.npcRole === "equipment");
assert.equal(talent.items.length, 4); assert.equal(new Set(talent.items.map((row) => row.item.job)).size, 4);
assert.equal(machines.items.length, 6);
for (const stage of ["opening", "carving", "finishing"]) assert.equal(machines.items.filter((row) => row.item.stage === stage).length, 2);
const npcEmployee = talent.items[0], npcDevice = machines.items[0];
assert.equal(buyGoodsFromStallForPlayer(buyer, talent.id, npcEmployee.id, npcEmployee.price).ok, true);
assert.equal(buyGoodsFromStallForPlayer(buyer, machines.id, npcDevice.id, npcDevice.price).ok, true);
assert.equal(buyGoodsFromStallForPlayer(buyer, machines.id, npcDevice.id).ok, false);
assert.ok(bmSellables({ me: buyer }).some((item) => item.id === npcEmployee.item.id));
assert.ok(bmSellables({ me: buyer }).some((item) => item.id === npcDevice.item.id));
buyer.workshop.devices = [];
H.normalizePlayer(buyer);
assert.equal(buyer.workshop.devices.length, 0, "selling the final device must not regenerate starter grants");
const offline = player("offline-resource-seller");
const offlineWorker = H.recruitWorker(offline, offline.recruitCandidates[0].id, { spendCash: H.spendCash }).worker;
openBlackStallForPlayer(offline, { type: "goods" });
assert.equal(addGoodsBatchToStallForPlayer(offline, [{ type: "employee", itemId: offlineWorker.id, price: 18000 }]).ok, true);
const offlineStall = H.state.blackStalls.find((stall) => stall.ownerId === offline.id);
const lastBusinessDay = offline.employeePayroll.businessDay;
const realNow = Date.now;
try {
  Date.now = () => realNow() + 3 * 86400000;
  assert.equal(buyGoodsFromStallForPlayer(buyer, offlineStall.id, offlineStall.items[0].id).ok, true);
  assert.equal(offline.employeePayroll.businessDay, lastBusinessDay, "offline transfer never starts a new payroll day");
  assert.ok(offline.employeePayroll.currentBill.entries.filter((entry) => entry.workerId !== offlineWorker.id).every((entry) => !entry.booked), "other offline employees do not receive a passive salary charge");
} finally { Date.now = realNow; }
console.log("blackmarket-resources-smoke: NPC supply, resale, payroll, locking, capacity, repricing, rollback, withdrawal and save/restore ok");
